def clean_reader_text(text):
    # MM p.70: Mimic SIZE is L; the scan OCR reads it as I.
    if '拟身怪' in text:
        text = re.sub(r'(体型</td><td[^>]*>)I(</td>)', r'\1L\2', text, flags=re.I)

    for old, new in REPLACEMENTS.items():
        text = text.replace(old, new)
    text = re.sub(r"(?:^|\n)## 本卷完成范围\s*\n[^\n]*(?:\n|$)", "\n", text)
    text = re.sub(r"<p\b[^>]*>[^<]*(?:译稿状态：|整页扫描仅供 OCR 核对)[^<]*</p>", "", text, flags=re.I)
    text = re.sub(r"<p\b[^>]*>[^<]*OCR 仅作底稿[^<]*</p>", "", text, flags=re.I)
    text = re.sub(r"<a\b[^>]*>[^<]*(?:译稿编务说明|本卷完成范围|本译稿的图表与校订)[^<]*</a>", "", text, flags=re.I)
    # Each pattern targets editorial prose, never tables, anchors or source-page comments.
    text = re.sub(r"[；，][^。；，<>\n]*后续(?:资源阶段将|资源阶段)?制作[^。<>\n]*。", "。", text)
    text = re.sub(r"[；，][^。；，<>\n]*列入后续插图资源阶段。", "。", text)
    text = re.sub(r"下一批(?:继续|从|进入)[^。<>\n]*。", "", text)
    text = re.sub(r"本批译文覆盖[^。<>\n]*。", "", text)
    text = re.sub(r"本页按双栏 OCR 顺序与原图逐句核对。", "", text)
    text = re.sub(r"原书逐一给出护甲等级、生命值、攻击次数、职业等级、灵能等级和属性；后续批次将继续按相同统计块格式录入。", "", text)
    text = text.replace("本批还出现了", "其他英雄与神祇包括")
    text = text.replace("首批末页开始出现", "其他人物包括")
    text = text.replace("他们的完整统计块与故事将在后续批次继续录入；", "")
    text = re.sub(r"<p\b[^>]*>\s*</p>", "", text, flags=re.I)
    return text


def is_editorial_title(title):
    return any(label in title for label in ("译稿编务说明", "本卷完成范围", "本译稿的图表与校订"))


