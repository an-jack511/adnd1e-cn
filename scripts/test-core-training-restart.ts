import assert from 'node:assert/strict';
import {newCoreAdvancement,awardAdventureXp,openAdvancementCandidate,attachTrainingPlan,payTraining,startTraining,recordTrainingSegment,interruptTraining,restartInterruptedTraining} from '../src/character/workflows/core-advancement';
let state=newCoreAdvancement({id:'restart',classId:'fighter',level:1,xp:0,constitution:10,levelCap:'unlimited'});
state=awardAdventureXp(state,{id:'adventure',xp:2100,rating:'S',sourceIds:['session:test']});
state=openAdvancementCandidate(state);
state=attachTrainingPlan(state,{route:'tutor',acceptedCostCp:600000});
state=payTraining(state,{paymentId:'lost-payment',amountCp:600000});
state=startTraining(state);
state=recordTrainingSegment(state,{id:'lost-week',weeksNumerator:1,weeksDenominator:1,dmConfirmedContinuous:true});
state=interruptTraining(state,{actorId:'dm',reason:'Serious hiatus, not a minor pause'});
const old=structuredClone(state);
assert.throws(()=>restartInterruptedTraining(state,{actorId:'dm',reason:' '}),/reason/);
state=restartInterruptedTraining(state,{actorId:'dm',reason:'Begin a fresh course under DMG86'});
assert.deepEqual(old.candidate?.paymentsCp,[600000]);
assert.equal(state.status,'training-planned');
assert.equal(state.xp,2100);assert.equal(state.level,1);
assert.deepEqual(state.assessments,old.assessments);
assert.deepEqual(state.candidate?.paymentsCp,[]);assert.deepEqual(state.candidate?.segments,[]);
assert.equal(state.candidate?.training,null);assert.equal(state.candidate?.acceptedCostCp,null);
assert.deepEqual(state.history.at(-1)?.abandonedCourse,old.candidate);
assert.throws(()=>startTraining(state),/not planned/);
state=attachTrainingPlan(state,{route:'tutor',acceptedCostCp:600000});
assert.throws(()=>startTraining(state),/not been paid/);
assert.throws(()=>payTraining(state,{paymentId:'lost-payment',amountCp:600000}),/Duplicate/);
state=payTraining(state,{paymentId:'new-payment',amountCp:600000});state=startTraining(state);
assert.equal(state.status,'training-active');assert.deepEqual(state.candidate?.segments,[]);
assert.throws(()=>restartInterruptedTraining(state,{actorId:'dm',reason:'retry'}),/No seriously/);
console.log('PASS: serious interruption restarts without refund, reused payment or retained progress; abandoned course preserved.');
