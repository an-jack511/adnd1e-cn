import assert from 'node:assert/strict';
import { blankCard, collectionNames, normalizeCard, selectPrepared } from '../src/character/ref2/model';

const legacy={character_id:'old-id',name:'艾琳',race:'human',class:'magic-user',STR:'12',ac:'8',weapon_0_name:'dagger',weapon_0_sm:'1d4',gear_0_item:'绳索',gear_0_quantity:'0',spell_0:'water',spell_1:'water',spell_2:'bless',unarmed_style:'拳击',unarmed_effect:'1d3',henchmen:'旧版随从附注',proficiencies:'裁缝（INT／+4）',family_notes:'家人记录',special_unknown:'保留的扩展'};
const migrated=normalizeCard(legacy);
assert.equal(migrated.fields.character_id,'old-id');
assert.equal(migrated.fields.henchmen,'旧版随从附注');
assert.equal(migrated.fields.special_unknown,'保留的扩展');
assert.equal(migrated.fields.manual_ac,true);
assert.equal(migrated.rows.weapons[0].values.name,'dagger');
assert.equal(migrated.rows.gear[0].values.quantity,'0');
assert.equal(migrated.rows.unarmed[0].values.style,'拳击');
assert.equal(migrated.rows.unarmed[0].values.damage,'1d3');
assert.deepEqual(migrated.preparedSpells,[{spellId:'water',count:2,expended:0},{spellId:'bless',count:1,expended:0}]);
for(const key of collectionNames)migrated.rows[key].push({id:`additional-${key}`,values:{name:`追加${key}`,background:'包含换行\n与 & 标点'}});
migrated.preparedSpells[0].expended=1;
migrated.futureExtension={keep:true};
assert.deepEqual(normalizeCard(JSON.parse(JSON.stringify(migrated))),migrated,'Every repeated record and extension must survive an export/import round trip');
selectPrepared(migrated,['water','drink','drink']);
assert.deepEqual(migrated.preparedSpells,[{spellId:'water',count:2,expended:1},{spellId:'drink',count:1,expended:0}]);
const empty=blankCard();empty.rows.henchmen=[];
assert.equal(normalizeCard(JSON.parse(JSON.stringify(empty))).rows.henchmen.length,0,'An intentionally empty section stays empty');
assert.throws(()=>normalizeCard({format:'campaign-archive',name:'other'}));
assert.throws(()=>normalizeCard({format:'adnd1e-ref2-card',version:99}));
assert.throws(()=>normalizeCard({...blankCard(),rows:{}}));
assert.throws(()=>normalizeCard({...blankCard(),preparedSpells:[{spellId:42}]}));
const overused=blankCard();overused.preparedSpells=[{spellId:'water',count:2,expended:20}];
assert.equal(normalizeCard(overused).preparedSpells[0].expended,2);
console.log('PASS: REF2 legacy migration, repeatable sections, complete JSON round trip, prepared spell counts and rejection of incompatible/corrupt files.');
