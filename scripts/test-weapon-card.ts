import assert from 'node:assert/strict';
import {items} from '../src/data/public/items';
import {blankCard,blankRow,normalizeCard} from '../src/character/ref2/model';
import {fillWeapon,selectWeapons} from '../src/character/ref2/weapons';
import {canonicalItemId} from '../src/utils/merge-ua-equipment';
const get=(id:string)=>{const item=items.find(item=>item.id===canonicalItemId(id));assert.ok(item,id);return item;};
const sword=get('ua-weapon-sword-short'),dagger=get('ua-weapon-dagger'),bow=get('ua-weapon-crossbow-heavy');
const row=blankRow();row.values={thac0:'17',hit:'+2',damage_adj:'+3',custom:'保留扩展'};
fillWeapon(row,sword);
assert.equal(row.values.speed,'3');assert.equal(row.values.length,'c. 2′');assert.equal(row.values.space,'1′');
assert.equal(row.values.sm,sword.damageSmallMedium);assert.equal(row.values.large,sword.damageLarge);
assert.equal(row.values.ac_0,'−5');assert.equal(row.values.ac_10,'+2');assert.ok(row.values.notes.includes('速3'));
fillWeapon(row,dagger,'missile');
assert.equal(row.values.attacks,'2');assert.equal(row.values.ac_0,'−7');assert.equal(row.values.mode,'missile');assert.ok(row.values.notes.includes('短1／中2／远3'));
fillWeapon(row,dagger,'handHeld');
assert.equal(row.values.ac_0,'−4');assert.equal(row.values.speed,'2');assert.equal(row.values.attacks,'');assert.ok(!row.values.notes.includes('短1'));
for(const [key,value] of Object.entries({thac0:'17',hit:'+2',damage_adj:'+3',custom:'保留扩展'}))assert.equal(row.values[key],value);
fillWeapon(row,bow);assert.equal(row.values.mode,'missile');assert.equal(row.values.attacks,'1/2');assert.equal(row.values.ac_10,'+4');
const card=blankCard();card.rows.weapons[0].values={name:'手造武器',notes:'原附注'};
card.rows.weapons[1].values={name:'future-weapon',weaponPickerId:'future-weapon',hit:'+4'};
selectWeapons(card,[sword.id,'backpack'],items);
const selected=card.rows.weapons.find(r=>r.values.name===sword.id)!;assert.ok(selected);assert.equal(card.rows.weapons.length,6);
selected.values.sm='1d6+2';selected.values.thac0='18';selected.values.notes='自定义战术';
selectWeapons(card,[sword.id,dagger.id],items);
assert.equal(card.rows.weapons.filter(r=>r.values.name===sword.id).length,1);assert.equal(selected.values.sm,'1d6+2');assert.equal(selected.values.notes,'自定义战术');
selectWeapons(card,[dagger.id],items);assert.ok(!card.rows.weapons.includes(selected));
assert.ok(card.rows.weapons.some(r=>r.values.name==='手造武器'));assert.ok(card.rows.weapons.some(r=>r.values.name==='future-weapon'));
assert.ok(!card.rows.gear.some(r=>r.values.itemId===dagger.id),'Combat selection must not duplicate carried weight in inventory');
assert.deepEqual(normalizeCard(JSON.parse(JSON.stringify(card))),card);
console.log('PASS: printed AC 0–10 mapping, separate melee/missile data, preserved personal bonuses, picker overrides, custom rows, no duplicate inventory and lossless card round-trip.');

const isolated=blankCard();selectWeapons(isolated,['dla-dragonlance','backpack',sword.id],items);
assert.deepEqual(isolated.rows.weapons.filter(row=>row.values.name).map(row=>row.values.name),[sword.id]);
console.log('PASS: magic items and gear cannot enter the ordinary weapon picker.');
